// cmhm_core/src/context/runtime.rs
//! ContextRuntime: the top-level Context OS orchestrator.
//!
//! Holds the Registry (persisted metadata) and Cache (live engine handles).
//! All MCP tool calls go through ContextRuntime.
//!
//! Thread-safety: wrapped in Arc<Mutex<ContextRuntime>> by the MCP server.

use anyhow::Result;
use std::collections::HashSet;
use std::io::BufRead;

use crate::{
    config::Config,
    engine::{self, EngineHandle, LearnResult},
    node::NodeType,
    retrieval::RetrievalResult,
};
use super::{
    ContextId, ContextMeta, ContextType, ContextState, ContextDescriptor,
    registry::Registry,
    cache::{ContextCache, context_snapshot_path, ensure_context_dir},
    router::{RouterWeights, top_k},
};

/// The name of the automatic default context.
const DEFAULT_CTX_NAME: &str = "default";

pub struct ContextRuntime {
    registry:         Registry,
    cache:            ContextCache,
    cfg:              Config,
    /// UUID v4 generated at server startup. Constant for the life of the process.
    /// Written into every learn-archive and retrieve-log entry for cross-log joining.
    session_id:       String,
    /// retrieve_ids for which feedback has already been applied.
    /// Loaded from feedback_ledger.jsonl on startup; appended on each feedback call.
    /// Enforces idempotency: repeated feedback with the same retrieve_id is a no-op.
    feedback_applied: HashSet<String>,
}

/// Safety-net: save registry metadata on drop even without explicit shutdown().
/// This ensures version/learn_count survive unexpected drops (crashes, test teardowns).
/// A clean shutdown() is still preferred — it also checkpoints the engine state.
impl Drop for ContextRuntime {
    fn drop(&mut self) {
        let _ = self.registry.save();
    }
}

impl ContextRuntime {
    /// Initialise the Context Runtime.
    /// `session_id` must be a UUID v4 generated by the caller at process startup.
    /// Loads the registry and feedback ledger from disk; does NOT pre-load any engine.
    pub fn new(cfg: Config, session_id: String) -> Result<Self> {
        std::fs::create_dir_all(&cfg.data_dir)?;
        std::fs::create_dir_all(cfg.data_dir.join("contexts"))?;
        std::fs::create_dir_all(&cfg.projections_dir)?;

        let registry = Registry::load(&cfg.data_dir)?;
        let max_active = cfg.max_active_contexts;
        let cache = ContextCache::new(max_active);
        let feedback_applied = load_feedback_ledger(&cfg.data_dir);

        let mut rt = Self { registry, cache, cfg, session_id, feedback_applied };

        // Ensure the "default" context always exists for backward-compat
        if rt.registry.find_by_name(DEFAULT_CTX_NAME).is_none() {
            let meta = ContextMeta::new(
                DEFAULT_CTX_NAME,
                ContextType::Project,
                None,
                "Auto-created default context for backward compatibility",
                vec!["default".to_string()],
            );
            rt.registry.create(meta)?;
        }

        Ok(rt)
    }

    /// UUID v4 that identifies this server process instance.
    /// Constant for the process lifetime — use to join entries across log files.
    pub fn session_id(&self) -> &str { &self.session_id }

    /// Return the root data directory for this runtime.
    /// Used by the MCP layer to locate sidecar files (retrieve_log.jsonl, learn_log.jsonl, etc.).
    pub fn data_dir(&self) -> &std::path::Path {
        &self.cfg.data_dir
    }

    // ── Feedback idempotency ─────────────────────────────────────────────────

    /// Returns true if feedback for this retrieve_id has already been applied.
    /// Always returns false if retrieve_id is None (non-tracked calls are never considered applied).
    pub fn is_feedback_applied(&self, retrieve_id: &str) -> bool {
        self.feedback_applied.contains(retrieve_id)
    }

    /// Mark a retrieve_id as having had its feedback applied and persist to ledger.
    /// Idempotent: calling twice for the same ID is safe (second call is no-op on the set).
    /// Ledger write failure emits tracing::warn! but never fails the feedback call.
    ///
    /// # Crash-boundary analysis
    ///
    /// There are two possible orderings, each with a crash window:
    ///
    /// **Option A — mutate, then record (current)**
    /// ```text
    /// feedback_nodes() mutates Beta(α,β)   ← crash here →   ledger.append(retrieve_id)
    /// ```
    /// On crash: ledger missing entry → next call re-applies feedback.
    /// Effect: Beta(α,β) incremented twice. Minor statistical bias (bounded, auto-correcting
    /// with subsequent feedback). NOT a correctness failure.
    ///
    /// **Option B — record, then mutate**
    /// ```text
    /// ledger.append(retrieve_id)   ← crash here →   feedback_nodes() mutates Beta
    /// ```
    /// On crash: ledger has entry → next call skips mutation entirely.
    /// Effect: feedback is silently and permanently lost. Worse than Option A.
    ///
    /// **Conclusion**: Option A (current) is correct. Double-apply on crash replay is a
    /// statistically minor, bounded Beta bias — not a data-loss event. Beta(α+1,β) applied
    /// twice is equivalent to Beta(α+2,β), which stays within [0,∞) regardless of k.
    ///
    /// If zero-tolerance is required, route feedback through the WAL as a `FeedbackNodes`
    /// command entry (mirroring `WalLearnEntry`). That would make feedback crash-safe at the
    /// cost of WAL growth. Deferred until the cost is justified by real usage data.
    pub fn record_feedback_applied(
        &mut self,
        retrieve_id: &str,
        ctx_id: &str,
        outcome: &str,
        node_ids: &[u64],
    ) {
        if self.feedback_applied.insert(retrieve_id.to_string()) {
            // First time — persist to ledger
            let path = self.cfg.data_dir.join("feedback_ledger.jsonl");
            let ts = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_millis())
                .unwrap_or(0);
            let line = format!(
                "{{\"retrieve_id\":\"{}\",\"ctx_id\":\"{}\",\"outcome\":\"{}\",\"node_ids\":{:?},\"ts\":{}}}\n",
                retrieve_id, ctx_id, outcome, node_ids, ts
            );
            use std::io::Write;
            if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(&path) {
                if f.write_all(line.as_bytes()).is_err() {
                    tracing::warn!(
                        retrieve_id,
                        "record_feedback_applied: failed to write to feedback_ledger.jsonl"
                    );
                }
            } else {
                tracing::warn!(
                    retrieve_id,
                    "record_feedback_applied: failed to open feedback_ledger.jsonl"
                );
            }
        }
    }

    // ── Context Lifecycle API ────────────────────────────────────────────────

    /// Create a new context. Returns its descriptor.
    pub fn create_context(
        &mut self,
        display_name: impl Into<String>,
        context_type: ContextType,
        parent_id: Option<ContextId>,
        description: impl Into<String>,
        tags: Vec<String>,
    ) -> Result<ContextDescriptor> {
        let meta = ContextMeta::new(display_name, context_type, parent_id, description, tags);
        let desc = self.registry.create(meta)?;
        tracing::info!("Context created: {} ({})", desc.display_name, desc.id);
        Ok(desc)
    }

    /// List all non-deleted contexts.
    pub fn list_contexts(&self) -> Vec<ContextDescriptor> {
        self.registry.list()
    }

    /// Delete a context: shut down its engine, remove its data, mark deleted.
    pub fn delete_context(&mut self, id: &ContextId) -> Result<()> {
        // Check it exists and is not already deleted
        let meta = self.registry.get(id)
            .ok_or_else(|| anyhow::anyhow!("E_NOT_FOUND: {id}"))?;
        if meta.state == ContextState::Deleted {
            anyhow::bail!("E_CONTEXT_DELETED: already deleted");
        }
        // Guard: cannot delete the default context
        if meta.display_name == DEFAULT_CTX_NAME {
            anyhow::bail!("E_PROTECTED: cannot delete the default context");
        }

        // Evict from cache (shuts down engine, takes snapshot)
        self.cache.remove(id);

        // Remove data directory
        let ctx_dir = self.cfg.data_dir.join("contexts").join(id.as_str());
        if ctx_dir.exists() {
            std::fs::remove_dir_all(&ctx_dir)?;
        }

        // Mark deleted via FSM gate (validates current_state -> Deleted is legal)
        self.registry.transition(id, ContextState::Deleted)?;
        tracing::info!("Context deleted: {}", id);
        Ok(())
    }

    /// Get a descriptor for a single context.
    pub fn get_descriptor(&self, id: &ContextId) -> Option<ContextDescriptor> {
        self.registry.get(id).map(ContextDescriptor::from)
    }

    // ── Routing API ──────────────────────────────────────────────────────────

    /// Auto-select the best context for a query hint.
    /// Returns the best-matching descriptor and its score.
    pub fn route(&self, query_hint: &str) -> Option<(ContextDescriptor, f32)> {
        let all: Vec<&ContextMeta> = self.registry.list_all()
            .iter()
            .filter_map(|d| self.registry.get(&d.id))
            .filter(|m| m.state != ContextState::Deleted)
            .collect();

        let weights = RouterWeights::from_config(&self.cfg);
        let scored = top_k(&all, query_hint, &weights, 1);
        scored.into_iter().next().map(|(m, s)| (ContextDescriptor::from(m), s))
    }

    /// Top-K context suggestions for a query hint.
    pub fn route_top_k(&self, query_hint: &str, k: usize) -> Vec<(ContextDescriptor, f32)> {
        let all: Vec<&ContextMeta> = self.registry.list_all()
            .iter()
            .filter_map(|d| self.registry.get(&d.id))
            .filter(|m| m.state != ContextState::Deleted)
            .collect();

        let weights = RouterWeights::from_config(&self.cfg);
        top_k(&all, query_hint, &weights, k)
            .into_iter()
            .map(|(m, s)| (ContextDescriptor::from(m), s))
            .collect()
    }

    // ── Memory Operations API ────────────────────────────────────────────────

    /// Learn into a context with default trusted user context.
    pub fn learn(
        &mut self,
        context_id: Option<&str>,
        state_emb:   Vec<f32>,
        action_emb:  Vec<f32>,
        outcome_emb: Vec<f32>,
        prediction_error: f32,
        emotional_tag:    f32,
        model_id: &str,
        authority:  f32,
        provenance: String,
        supersedes: Option<u64>,
    ) -> Result<(LearnResult, ContextDescriptor)> {
        self.learn_with_context(
            context_id, state_emb, action_emb, outcome_emb,
            prediction_error, emotional_tag, model_id,
            authority, provenance, supersedes,
            crate::authority::CallerRole::User,
            None,
            None,
        )
    }

    /// Learn into a context with caller ingestion role and optional semantic assertion fields.
    pub fn learn_with_context(
        &mut self,
        context_id: Option<&str>,
        state_emb:   Vec<f32>,
        action_emb:  Vec<f32>,
        outcome_emb: Vec<f32>,
        prediction_error: f32,
        emotional_tag:    f32,
        model_id: &str,
        authority:  f32,
        provenance: String,
        supersedes: Option<u64>,
        caller_role: crate::authority::CallerRole,
        assertion_key: Option<String>,
        polarity: Option<i8>,
    ) -> Result<(LearnResult, ContextDescriptor)> {
        let id = self.resolve_context(context_id)?;
        let handle = self.ensure_loaded(&id)?;
        let result = handle.learn_with_context(
            state_emb, action_emb, outcome_emb,
            prediction_error, emotional_tag, model_id,
            authority, provenance, supersedes,
            caller_role, assertion_key, polarity,
        )?;
        self.registry.record_learn(&id);
        let desc = self.registry.get(&id)
            .map(ContextDescriptor::from)
            .ok_or_else(|| anyhow::anyhow!("context vanished after learn"))?;
        Ok((result, desc))
    }



    /// Retrieve from a context. If context_id is None, uses the default context.
    ///
    /// `seed_type` is mandatory — unscoped retrieval is not permitted from the public API.
    pub fn retrieve(
        &mut self,
        context_id: Option<&str>,
        query_emb: Vec<f32>,
        model_id:  &str,
        seed_type: NodeType,
    ) -> Result<(RetrievalResult, ContextDescriptor)> {
        let id = self.resolve_context(context_id)?;
        let handle = self.ensure_loaded(&id)?;
        let result = handle.retrieve(query_emb, model_id, seed_type)?;
        // ensure_loaded already called transition -> Active
        let desc = self.registry.get(&id)
            .map(ContextDescriptor::from)
            .ok_or_else(|| anyhow::anyhow!("context vanished after retrieve"))?;
        Ok((result, desc))
    }

    /// Unscoped retrieval — all NodeType variants compete in the candidate pool.
    ///
    /// Used when `retrieval_intent` is absent from the MCP call, or when a
    /// benchmark must verify cross-type contradiction safety without type fencing.
    pub fn retrieve_unscoped(
        &mut self,
        context_id: Option<&str>,
        query_emb: Vec<f32>,
        model_id:  &str,
    ) -> Result<(RetrievalResult, ContextDescriptor)> {
        let id = self.resolve_context(context_id)?;
        let handle = self.ensure_loaded(&id)?;
        let result = handle.retrieve_unscoped(query_emb, model_id)?;
        let desc = self.registry.get(&id)
            .map(ContextDescriptor::from)
            .ok_or_else(|| anyhow::anyhow!("context vanished after retrieve_unscoped"))?;
        Ok((result, desc))
    }


    /// Maximum cosine similarity between `query_emb` and existing nodes of `node_type` in a context.
    ///
    /// Used by the shadow gate: `novelty = 1.0 - max_cosine_in_context(...)`.
    /// Pass `NodeType::State` for the standard state-novelty check (role-scoped).
    /// Returns `0.0` on empty or unloaded context (novelty = 1.0, gate score maximised).
    /// Does NOT load the context — if it's sleeping, we skip the novelty check (safe: returns 0).
    pub fn max_cosine_in_context(
        &mut self,
        context_id: Option<&str>,
        query_emb: &[f32],
        model_id: &str,
        node_type: NodeType,
    ) -> f32 {
        let id = match self.resolve_context(context_id) {
            Ok(id) => id,
            Err(_) => return 0.0,
        };
        // Only check if context is already loaded — avoid a disk load just for shadow gate
        match self.cache.get(&id) {
            Some(handle) => handle.max_cosine_to_existing(query_emb, model_id, Some(node_type)),
            None => 0.0, // not loaded → treat as novel
        }
    }

    /// Force a snapshot of a context.
    pub fn checkpoint(&mut self, context_id: Option<&str>) -> Result<ContextDescriptor> {
        let id = self.resolve_context(context_id)?;
        if self.cache.is_loaded(&id) {
            let snap = context_snapshot_path(&self.cfg.data_dir, &id);
            if let Some(handle) = self.cache.get(&id) {
                handle.snapshot(snap)?;
            }
        }
        self.registry.get(&id)
            .map(ContextDescriptor::from)
            .ok_or_else(|| anyhow::anyhow!("E_NOT_FOUND: {id}"))
    }

    /// Stats for a context.
    pub fn stats(&mut self, context_id: Option<&str>) -> Result<ContextStats> {
        let id = self.resolve_context(context_id)?;
        let meta = self.registry.get(&id)
            .ok_or_else(|| anyhow::anyhow!("E_NOT_FOUND: {id}"))?;
        Ok(ContextStats {
            descriptor:          ContextDescriptor::from(meta),
            is_loaded:           self.cache.is_loaded(&id),
            active_count:        self.cache.active_count(),
            max_active_contexts: self.cfg.max_active_contexts,
        })
    }

    /// Merge keyword tags into a context's routing metadata.
    ///
    /// Automatically called after `memory_learn_text` to improve future
    /// `context_route` accuracy. Tags are lowercased, deduplicated, and capped
    /// at 64 per context. Persists to the registry on disk.
    ///
    /// Pass `context_id = None` to target the default context.
    pub fn add_tags(&mut self, context_id: Option<&str>, new_tags: Vec<String>) -> Result<()> {
        let id = self.resolve_context(context_id)?;
        self.registry.add_tags(&id, new_tags, 64)
    }

    /// Provide outcome feedback for a list of node IDs after a retrieve → act → observe cycle.
    ///
    /// Updates each node's Beta(α, β) bandit posterior and half-life.
    /// `feedback_key`: stable base key for per-node deduplication (typically the retrieve_id).
    /// When provided, the engine skips any (key, node_id, outcome) triple it has already applied.
    /// Returns (updated_count, ContextDescriptor).
    pub fn feedback_nodes(
        &mut self,
        context_id: Option<&str>,
        node_ids: Vec<u64>,
        success: bool,
        feedback_key: Option<String>,
    ) -> Result<(usize, ContextDescriptor)> {
        let id = self.resolve_context(context_id)?;
        let handle = self.ensure_loaded(&id)?;
        let updated = handle.feedback_nodes(node_ids, success, feedback_key)?;
        let desc = self.registry.get(&id)
            .map(ContextDescriptor::from)
            .ok_or_else(|| anyhow::anyhow!("context vanished after feedback"))?;
        Ok((updated, desc))
    }

    /// Number of nodes in the default (or specified) context's node store.
    /// Read-only — no WAL write. Returns 0 if context is not loaded or on error.
    /// Used by tests to assert insertion without depending on retrieval traversal.
    pub fn node_count(&mut self, context_id: Option<&str>) -> usize {
        let id = match self.resolve_context(context_id) {
            Ok(id) => id,
            Err(_) => return 0,
        };
        match self.ensure_loaded(&id) {
            Ok(handle) => handle.node_count(),
            Err(_) => 0,
        }
    }

    /// Beta posterior `(bandit_alpha, bandit_beta)` for a specific node ID in the given context.
    /// Returns `None` if the context is not loaded, or if the node ID is absent.
    /// Read-only — no WAL write. Used by tests to verify Beta parameter correctness.
    pub fn get_node_beta(&mut self, context_id: Option<&str>, node_id: u64) -> Option<(f32, f32)> {
        let id = self.resolve_context(context_id).ok()?;
        let handle = self.ensure_loaded(&id).ok()?;
        handle.get_node_beta(node_id)
    }

    /// Current value of the adaptive birth gate quantile (P₀.₃₀ estimator).
    /// Returns 0.30 (the default prior) if the context is not loaded.
    /// Read-only — no WAL write. Used by tests to verify quantile convergence.
    pub fn get_birth_q30(&mut self, context_id: Option<&str>) -> f32 {
        let id = match self.resolve_context(context_id) { Ok(i) => i, Err(_) => return 0.30 };
        let handle = match self.ensure_loaded(&id) { Ok(h) => h, Err(_) => return 0.30 };
        handle.get_birth_q30()
    }

    /// Graceful shutdown: checkpoint all loaded contexts.
    pub fn shutdown(&mut self) {
        // Transition all loaded Active/Idle contexts to Sleeping so registry
        // reflects correct state on next startup.
        let loaded_ids: Vec<ContextId> = self.cache.loaded_ids();
        for id in &loaded_ids {
            let state = self.registry.get(id).map(|m| m.state);
            if state == Some(ContextState::Active) || state == Some(ContextState::Idle) {
                let _ = self.registry.transition(id, ContextState::Sleeping);
            }
        }
        self.cache.checkpoint_all(&self.cfg.data_dir.clone());
        self.cache.shutdown_all();
        let _ = self.registry.save();
    }

    // ── Internal helpers ─────────────────────────────────────────────────────

    /// Resolve an optional context_id string to a ContextId.
    /// None → "default" context.
    /// Also accepts display names for convenience.
    fn resolve_context(&self, context_id: Option<&str>) -> Result<ContextId> {
        let name = context_id.unwrap_or(DEFAULT_CTX_NAME);

        // First try exact UUID match
        let probe = ContextId::from_str(name);
        if let Some(m) = self.registry.get(&probe) {
            if m.state != ContextState::Deleted {
                return Ok(probe);
            } else {
                anyhow::bail!("E_CONTEXT_DELETED: {name}");
            }
        }

        // Fallback: match by display name
        if let Some(m) = self.registry.find_by_name(name) {
            return Ok(m.id.clone());
        }

        anyhow::bail!("E_NOT_FOUND: context '{}' does not exist. Use context_create first.", name)
    }

    /// Ensure a context's engine is loaded in the cache.
    /// If not loaded, starts a new engine from the existing snapshot (if any).
    ///
    /// Crash recovery path:
    ///   - If the context is Sleeping and a WAL file exists alongside the snapshot,
    ///     we transition it to Recovering before starting the engine.
    ///     The engine replays the WAL on startup. On success we transition to Active.
    ///   - If the context is Sleeping with no WAL (clean shutdown), we go directly
    ///     Creating -> Active... wait, state is Sleeping -> Active (clean load).
    fn ensure_loaded(&mut self, id: &ContextId) -> Result<&EngineHandle> {
        use crate::context::cache::context_wal_path;

        if !self.cache.is_loaded(id) {
            tracing::info!("Loading context {} into RAM", id);
            ensure_context_dir(&self.cfg.data_dir, id)?;

            // --- State classification for loading ---
            // A context might be Sleeping (clean eviction or clean shutdown),
            // Active (saved by old code / partial shutdown), or Creating (new).
            // If WAL exists, we need recovery regardless of the recorded state.
            let current_state = self.registry.get(id)
                .map(|m| m.state)
                .unwrap_or(ContextState::Creating);

            let wal_path = context_wal_path(&self.cfg.data_dir, id);
            let needs_recovery = wal_path.exists() && matches!(
                current_state,
                ContextState::Sleeping | ContextState::Active | ContextState::Idle
            );

            if needs_recovery {
                // Ensure we're in Sleeping before transitioning to Recovering
                if current_state == ContextState::Active || current_state == ContextState::Idle {
                    let _ = self.registry.transition(id, ContextState::Sleeping);
                }
                tracing::warn!("Context {} has unclean WAL -- entering Recovering state", id);
                if let Err(e) = self.registry.transition(id, ContextState::Recovering) {
                    tracing::error!("Could not enter Recovering state for {}: {e}", id);
                }
            } else if current_state == ContextState::Active || current_state == ContextState::Idle {
                // Context was saved as Active/Idle (old shutdown or partial flush).
                // Treat as Sleeping for the load path.
                let _ = self.registry.transition(id, ContextState::Sleeping);
            }

            let ctx_dir = self.cfg.data_dir.join("contexts").join(id.as_str());
            let mut ctx_cfg = self.cfg.clone();
            ctx_cfg.data_dir = ctx_dir;

            let handle = match engine::start(ctx_cfg) {
                Ok(h) => h,
                Err(e) => {
                    if needs_recovery {
                        if e.downcast_ref::<crate::engine::SchemaMismatchError>().is_some() {
                            // Schema mismatch (fail-closed): engine::start() left both the
                            // snapshot and WAL byte-for-byte untouched — no data was written.
                            // Roll the context back to Sleeping so its UUID stays registered.
                            // The operator can then inspect, restore from backup, provide a
                            // migration, or set allow_incompatible_snapshot_reset=true.
                            tracing::error!(
                                "Context {id}: snapshot schema mismatch -- context preserved \
                                 in Sleeping state (UUID intact). Snapshot and WAL are \
                                 untouched. Set allow_incompatible_snapshot_reset=true \
                                 to quarantine and reset, or provide a migration path."
                            );
                            let _ = self.registry.transition(id, ContextState::Sleeping);
                        } else {
                            // Genuine WAL replay failure or other startup error.
                            // Context data may be irrecoverably corrupt; mark Deleted.
                            tracing::error!("WAL replay failed for context {}: {e}", id);
                            let _ = self.registry.transition(id, ContextState::Deleted);
                        }
                    }
                    return Err(e);
                }
            };

            let evicted = self.cache.insert(id.clone(), handle);
            if let Some(evicted_id) = evicted {
                let evicted_state = self.registry.get(&evicted_id)
                    .map(|m| m.state)
                    .unwrap_or(ContextState::Active);
                if evicted_state == ContextState::Active || evicted_state == ContextState::Idle {
                    let _ = self.registry.transition(&evicted_id, ContextState::Sleeping);
                }
            }

            // Transition to Active (from Creating, Sleeping, or Recovering)
            self.registry.transition(id, ContextState::Active)?;

        } else {
            // Already in RAM: touch LRU.
            // If Idle, transition to Active (request arrived).
            // If already Active, just bump access stats directly — no state change needed.
            self.cache.touch(id);
            let current = self.registry.get(id).map(|m| m.state);
            if current == Some(ContextState::Idle) {
                // Idle -> Active (request arrived)
                let _ = self.registry.transition(id, ContextState::Active);
            } else if current == Some(ContextState::Active) {
                // Already Active: bump stats without touching state
                self.registry.record_access(id);
            }
        }

        self.cache.get(id)
            .ok_or_else(|| anyhow::anyhow!("internal: handle missing after ensure_loaded"))
    }

    /// Get the default context ID.
    pub fn default_context_id(&self) -> Option<ContextId> {
        self.registry.find_by_name(DEFAULT_CTX_NAME).map(|m| m.id.clone())
    }
}


// ── Stats ────────────────────────────────────────────────────────────────────

pub struct ContextStats {
    pub descriptor:          ContextDescriptor,
    pub is_loaded:           bool,
    /// How many contexts are currently loaded in RAM.
    pub active_count:        usize,
    /// The configured cap on simultaneous in-RAM contexts.
    pub max_active_contexts: usize,
}

// ── Feedback ledger loader ────────────────────────────────────────────────────

/// Load all retrieve_ids that have had feedback applied from `feedback_ledger.jsonl`.
/// Called once at runtime startup. Missing file → empty set (normal on first run).
/// Malformed lines are skipped (partial write during a crash is expected).
fn load_feedback_ledger(data_dir: &std::path::Path) -> HashSet<String> {
    let mut set = HashSet::new();
    let path = data_dir.join("feedback_ledger.jsonl");
    let f = match std::fs::File::open(&path) {
        Ok(f)  => f,
        Err(_) => return set, // first run or file missing — normal
    };
    for line in std::io::BufReader::new(f).lines() {
        let line = match line {
            Ok(l) if !l.trim().is_empty() => l,
            _ => continue,
        };
        // Extract retrieve_id from JSON line without pulling in a JSON parser here.
        // Line format: {"retrieve_id":"<uuid>",...}
        if let Some(id) = extract_string_field(&line, "retrieve_id") {
            set.insert(id);
        } else {
            tracing::debug!("load_feedback_ledger: skipping malformed line");
        }
    }
    tracing::debug!(
        count = set.len(),
        "load_feedback_ledger: loaded previously-applied feedback IDs"
    );
    set
}

/// Minimal string-field extractor for JSONL lines we write ourselves.
/// Finds `"key":"value"` and returns value. No dependency on serde here.
fn extract_string_field(line: &str, key: &str) -> Option<String> {
    let needle = format!("\"{}\":\"", key);
    let start = line.find(&needle)? + needle.len();
    let rest = &line[start..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}
